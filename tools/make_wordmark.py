#!/usr/bin/env python3
"""Generate the wordmark SVGs: letterforms filled with proof material.

    python tools/make_wordmark.py

Writes assets/oblivio-wordmark-mono.svg (black, light ground) and
assets/oblivio-wordmark-mono-inverse.svg (white, dark ground).

Why a generator rather than two hand-written files
--------------------------------------------------
The two differ only in ink. Hand-maintaining both guarantees they drift, and a
mark that renders differently on GitHub's two themes is worse than one that only
works on one -- at least the second failure is visible to its author.

The fill
--------
The glyphs are a `clipPath`, and what shows through is a real Merkle root: the
one printed by the membership demo in the README, repeated. So the wordmark is
made of the thing the project actually produces, and the digits are checkable
against a published value rather than invented to look cryptographic.

A faint solid backing sits under the hex at low opacity. Without it the rows
read as stripes and the letterforms come apart at README scale; with it the
shape holds and the hex still reads as the texture. Set BACKING to 0 to see the
difference.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The root printed by the succinct-membership demo in README.md. Real, published,
# and checkable -- not hex chosen to look the part.
MERKLE_ROOT = "1d5e3e4a5fb29328"

W, H = 340, 96
ANCHOR_X = 173.25      # 340/2 + half the letter-spacing; see the SVG comment
BASELINE = 62
FONT_SIZE = 40
TRACKING = 6.5
STACK = ("ui-sans-serif, -apple-system, 'Segoe UI', Roboto, "
         "Helvetica, Arial, sans-serif")

HEX_SIZE = 6           # small enough to read as texture, large enough to be legible
ROW_STEP = 6
ROW_TOP, ROW_BOTTOM = 32, 64   # covers the cap height (top ~34, baseline 62)
CHARS_PER_ROW = 100    # 340px / (6px * 0.6 advance) with margin
BACKING = 0.28         # opacity of the solid under the hex


def rows() -> list[tuple[int, str]]:
    """One (y, text) per row, each offset so the columns do not line up.

    Aligned rows would draw vertical seams straight down the letterforms, which
    reads as a printing fault rather than as texture.
    """
    out = []
    for i, y in enumerate(range(ROW_TOP, ROW_BOTTOM + 1, ROW_STEP)):
        shift = (i * 5) % len(MERKLE_ROOT)
        seed = MERKLE_ROOT[shift:] + MERKLE_ROOT[:shift]
        text = (seed * (CHARS_PER_ROW // len(seed) + 2))[:CHARS_PER_ROW]
        out.append((y, text))
    return out


def svg(ink: str, ground: str) -> str:
    band = "\n".join(
        f'      <text x="0" y="{y}" font-family="ui-monospace, SFMono-Regular, '
        f'Consolas, monospace" font-size="{HEX_SIZE}" fill="{ink}">{text}</text>'
        for y, text in rows())
    # NB: no "--" anywhere in the comment below. XML forbids it inside a comment,
    # and GitHub renders README SVGs through a sanitiser that drops the file
    # rather than repairing it, so the mark would simply not appear.
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}"
     role="img" aria-label="Oblivio">
  <title>Oblivio</title>
  <!-- GENERATED by tools/make_wordmark.py. Edit that, not this.

       The letterforms are a clipping path and what shows through them is a real
       Merkle root ({MERKLE_ROOT}, the one the README's membership demo prints),
       repeated with each row offset so the columns do not draw seams down the
       glyphs. The mark is made of the artefact the project produces.

       Ink is {ink} on a {ground} ground. The pair is switched by
       prefers-color-scheme in the README: a single-ink mark needs both inks, or
       half the readers get nothing.

       The wordmark is live <text>, so the clip depends on the reader's font
       stack. Convert to outlines before print, embroidery, or handing this to
       anyone whose renderer you do not control.

       Centred with text-anchor rather than a computed x: the stack resolves
       differently per platform and a measured offset is only centred on the
       machine that measured it. x is {ANCHOR_X} rather than {W // 2} because SVG
       adds the tracking after the final glyph too, so the advance being centred
       is {TRACKING}px wider than the ink. -->
  <defs>
    <clipPath id="oblivio-wordmark">
      <text x="{ANCHOR_X}" y="{BASELINE}" text-anchor="middle"
            font-family="{STACK}"
            font-size="{FONT_SIZE}" letter-spacing="{TRACKING}"
            font-weight="700">OBLIVIO</text>
    </clipPath>
  </defs>
  <g clip-path="url(#oblivio-wordmark)">
    <rect x="0" y="0" width="{W}" height="{H}" fill="{ink}" opacity="{BACKING}"/>
    <g letter-spacing="0.35">
{band}
    </g>
  </g>
</svg>
"""


def main() -> int:
    targets = [
        ("assets/oblivio-wordmark-mono.svg", "#000000", "light"),
        ("assets/oblivio-wordmark-mono-inverse.svg", "#FFFFFF", "dark"),
    ]
    for rel, ink, ground in targets:
        path = ROOT / rel
        path.write_text(svg(ink, ground), encoding="utf-8")
        print(f"wrote {rel}  ({ink} on {ground}, {len(rows())} hex rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
